package envtemplate

import (
	"fmt"
	"sort"
	"strings"

	"github.com/joeyvictorino/tasia/internal/collect"
)

type Category string

const (
	CatSecret      Category = "secret"
	CatConfig      Category = "config"
	CatFeatureFlag Category = "feature_flag"
)

type EnvVar struct {
	Key      string   `json:"key"`
	Value    string   `json:"value"`
	Category Category `json:"category"`
	Services []string `json:"services"`
}

type Report struct {
	Path    string   `json:"path"`
	Vars    []EnvVar `json:"vars"`
	Summary struct {
		Total        int `json:"total"`
		Secrets      int `json:"secrets"`
		Config       int `json:"config"`
		FeatureFlags int `json:"feature_flags"`
	} `json:"summary"`
}

var secretPatterns = []string{
	"password", "secret", "token", "key", "api_key", "apikey",
	"auth", "credential", "private", "cert", "ssl", "tls",
	"access_key", "secret_key", "jwt", "oauth", "encryption",
}

var featureFlagPatterns = []string{
	"enable", "disable", "flag", "feature", "toggle",
	"debug", "verbose", "mode",
}

func categorize(key string) Category {
	lower := strings.ToLower(key)
	for _, p := range secretPatterns {
		if strings.Contains(lower, p) {
			return CatSecret
		}
	}
	for _, p := range featureFlagPatterns {
		if strings.Contains(lower, p) {
			return CatFeatureFlag
		}
	}
	return CatConfig
}

func placeholder(key string, cat Category) string {
	switch cat {
	case CatSecret:
		return fmt.Sprintf("# %s — secret/credential (replace with actual value)", key)
	case CatFeatureFlag:
		return fmt.Sprintf("# %s — feature flag / toggle", key)
	default:
		return fmt.Sprintf("# %s — configuration value", key)
	}
}

func Analyze(c *collect.Collected) Report {
	r := Report{Path: c.Root}

	seen := map[string]*EnvVar{}
	for _, cf := range c.ComposeFiles {
		for _, svc := range cf.Services {
			for _, e := range svc.Environment {
				parts := strings.SplitN(e, "=", 2)
				key := parts[0]
				val := ""
				if len(parts) > 1 {
					val = parts[1]
				}
				if ev, ok := seen[key]; ok {
					found := false
					for _, s := range ev.Services {
						if s == svc.Name {
							found = true
							break
						}
					}
					if !found {
						ev.Services = append(ev.Services, svc.Name)
					}
				} else {
					cat := categorize(key)
					seen[key] = &EnvVar{
						Key:      key,
						Value:    val,
						Category: cat,
						Services: []string{svc.Name},
					}
				}
			}
		}
	}

	keys := make([]string, 0, len(seen))
	for k := range seen {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	for _, k := range keys {
		ev := seen[k]
		r.Vars = append(r.Vars, *ev)
		switch ev.Category {
		case CatSecret:
			r.Summary.Secrets++
		case CatFeatureFlag:
			r.Summary.FeatureFlags++
		default:
			r.Summary.Config++
		}
	}
	r.Summary.Total = len(r.Vars)
	return r
}

func FormatEnvExample(r Report) string {
	var b strings.Builder
	b.WriteString("# .env.example — Generated by tasia env-template\n")
	b.WriteString("# Replace placeholder values before use.\n\n")

	byCategory := map[Category][]EnvVar{
		CatSecret:      {},
		CatConfig:      {},
		CatFeatureFlag: {},
	}
	for _, v := range r.Vars {
		byCategory[v.Category] = append(byCategory[v.Category], v)
	}

	sections := []struct {
		cat   Category
		title string
	}{
		{CatSecret, "Secrets / Credentials"},
		{CatConfig, "Configuration"},
		{CatFeatureFlag, "Feature Flags"},
	}

	for _, sec := range sections {
		vars := byCategory[sec.cat]
		if len(vars) == 0 {
			continue
		}
		fmt.Fprintf(&b, "# === %s ===\n", sec.title)
		for _, v := range vars {
			fmt.Fprintf(&b, "%s\n", placeholder(v.Key, v.Category))
			fmt.Fprintf(&b, "# Used by: %s\n", strings.Join(v.Services, ", "))
			fmt.Fprintf(&b, "%s=\n\n", v.Key)
		}
	}

	return b.String()
}

func FormatText(r Report) string {
	var b strings.Builder
	b.WriteString("Environment Template Report\n")
	b.WriteString(strings.Repeat("=", 50) + "\n")
	fmt.Fprintf(&b, "Path: %s\n\n", r.Path)
	fmt.Fprintf(&b, "  Total variables:   %d\n", r.Summary.Total)
	fmt.Fprintf(&b, "  Secrets:           %d\n", r.Summary.Secrets)
	fmt.Fprintf(&b, "  Config:            %d\n", r.Summary.Config)
	fmt.Fprintf(&b, "  Feature flags:     %d\n\n", r.Summary.FeatureFlags)

	for _, v := range r.Vars {
		fmt.Fprintf(&b, "  %-30s [%s]  services=%s\n", v.Key, v.Category, strings.Join(v.Services, ","))
	}
	return b.String()
}
