func TestRenderHTMLStructure(t *testing.T) {
	findings := []rules.Finding{
		{ID: "exposed_inference", Severity: rules.SeverityHigh, Title: "Inference API published", File: "docker-compose.yml", Line: 12, Evidence: "port 11434", Why: "exposes model API", Fix: "bind to 127.0.0.1"},
		{ID: "privileged_container", Severity: rules.SeverityCritical, Title: "Privileged container", File: "docker-compose.yml", Line: 20, Evidence: "privileged: true", Why: "full host access", Fix: "remove privileged"},
	}
	summary := ScanSummary{
		TotalFindings: 2,
		BySeverity:    map[string]int{"CRITICAL": 1, "HIGH": 1, "MEDIUM": 0, "LOW": 0},
		ByCategory:    map[string]int{"compose": 2},
	}
	html := RenderHTML(findings, summary, "/test/path", "Test Report")

	checks := []struct {
		label string
		want  string
	}{
		{"doctype", "<!DOCTYPE html>"},
		{"title", "<title>Test Report</title>"},
		{"scan path", "/test/path"},
		{"total badge", "2"},
		{"critical badge", "Critical"},
		{"high badge", "High"},
		{"table header", "Severity"},
		{"rule id", "exposed_inference"},
		{"privileged rule", "privileged_container"},
		{"evidence", "port 11434"},
		{"fix text", "bind to 127.0.0.1"},
		{"footer", "Generated by"},
		{"severity class", "sev-CRITICAL"},
		{"sort script", "data-sort"},
	}

	for _, c := range checks {
		if !strings.Contains(html, c.want) {
			t.Errorf("%s: HTML should contain %q", c.label, c.want)
		}
	}
}

func TestRenderHTMLEmptyFindings(t *testing.T) {
	summary := ScanSummary{
		TotalFindings: 0,
		BySeverity:    map[string]int{"CRITICAL": 0, "HIGH": 0, "MEDIUM": 0, "LOW": 0},
	}
	html := RenderHTML(nil, summary, "/empty", "")

	if !strings.Contains(html, "Tasia Security Report") {
		t.Error("default title should be 'Tasia Security Report'")
	}
	if !strings.Contains(html, "0") {
		t.Error("should show 0 total")
	}
	if strings.Contains(html, "Critical") {
		t.Error("should not show Critical badge when count is 0")
	}
}

func TestRenderHTMLSeverityOrdering(t *testing.T) {
	findings := []rules.Finding{
		{ID: "low_rule", Severity: rules.SeverityLow, Title: "Low finding", File: "a.yml"},
		{ID: "crit_rule", Severity: rules.SeverityCritical, Title: "Critical finding", File: "b.yml"},
	}
	summary := ScanSummary{
		TotalFindings: 2,
		BySeverity:    map[string]int{"CRITICAL": 1, "HIGH": 0, "MEDIUM": 0, "LOW": 1},
	}
	html := RenderHTML(findings, summary, "/test", "Order Test")

	critIdx := strings.Index(html, "crit_rule")
	lowIdx := strings.Index(html, "low_rule")
	if critIdx > lowIdx {
		t.Error("critical findings should appear before low findings in the table")
	}
}

func TestRenderHTMLEscaping(t *testing.T) {
	findings := []rules.Finding{
		{ID: "test_rule", Severity: rules.SeverityHigh, Title: "Rule with <script>", File: "test.yml", Evidence: "a & b", Why: `"quoted"`, Fix: "use <safe>"},
	}
	summary := ScanSummary{
		TotalFindings: 1,
		BySeverity:    map[string]int{"CRITICAL": 0, "HIGH": 1, "MEDIUM": 0, "LOW": 0},
	}
	html := RenderHTML(findings, summary, "/test", "Escape <Test>")

	if !strings.Contains(html, "&lt;script&gt;") {
		t.Error("should contain escaped script tag in finding title")
	}
	if !strings.Contains(html, "Escape &lt;Test&gt;") {
		t.Error("should escape HTML in page title")
	}
	if !strings.Contains(html, "a &amp; b") {
		t.Error("should escape ampersands in evidence")
	}
}
